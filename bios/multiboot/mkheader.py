hook = int(sys.argv[3], 16)
print('/* Generated by bios/multiboot (make): do not edit. */')
print('#define BIOS_MULTIBOOT_ADDR  0x2440')
print('#define BIOS_MULTIBOOT_ENTRY 0x%04X' % entry)
print('#define BIOS_BOOTHOOK_ENTRY  0x%04X' % hook)
print('static const unsigned char bios_multiboot_block[%d] = {' % len(data))
for i in range(0, len(data), 12):
    print('  ' + ', '.join('0x%02X' % b for b in data[i:i + 12]) + ',')
print('};')
